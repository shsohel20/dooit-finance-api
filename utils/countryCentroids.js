/**
 * Resolve a country name to its centroid { lat, lng } or null if unknown.
 * Case/space tolerant + a few common aliases.
 */
function getCentroid(name) {
  if (!name || typeof name !== "string") return null;
  const trimmed = name.trim();
  if (COUNTRY_CENTROIDS[trimmed]) return COUNTRY_CENTROIDS[trimmed];

  const lower = trimmed.toLowerCase();
  if (ALIASES[lower]) return COUNTRY_CENTROIDS[ALIASES[lower]] || null;

  // case-insensitive direct match
  const key = Object.keys(COUNTRY_CENTROIDS).find(
    (k) => k.toLowerCase() === lower,
  );
  return key ? COUNTRY_CENTROIDS[key] : null;
}

