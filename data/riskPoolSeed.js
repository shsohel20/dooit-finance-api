const ne      = (field, value)       => ({ field, op: "not_equals",       value });
const neOpt   = (field, value)       => ({ field, op: "not_equals",       value, optional: true });
const any     = (field, values)      => ({ field, op: "includes_any",     values });
const anyOpt  = (field, values)      => ({ field, op: "includes_any",     values, optional: true });
const hasTxt  = (field, text)        => ({ field, op: "includes_text",    text });
const notTxt  = (field, text)        => ({ field, op: "not_includes_text",text });

// lMod helpers
